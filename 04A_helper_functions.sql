-- Returns grids part of a project
DROP FUNCTION IF EXISTS get_grids;
CREATE FUNCTION get_grids(project_id INT)
RETURNS TABLE(taskid INTEGER, geom GEOMETRY) AS $$
BEGIN
	RETURN QUERY
	SELECT g.taskid, g.geom
	FROM grids g
	WHERE g.project_id = get_grids.project_id;
END;
$$ LANGUAGE plpgsql;

-- Returns grids in UTM projection
DROP FUNCTION IF EXISTS get_grids_in_utm;
CREATE FUNCTION get_grids_in_utm(project_id INT, do_mockup_grid BOOLEAN DEFAULT FALSE)
RETURNS TABLE(taskid INTEGER, geom GEOMETRY) AS $$
BEGIN
	IF do_mockup_grid THEN
		RETURN QUERY
		SELECT mpg.taskid, mpg.geom FROM mockup_polygon_grids AS mpg
		WHERE mpg.project_id = get_grids_in_utm.project_id;
	ELSE
		RETURN QUERY
		SELECT g.taskid, g.geom_utm FROM grids g
		WHERE g.project_id = get_grids_in_utm.project_id;
	END IF;
END;
$$ LANGUAGE plpgsql;


-- Returns shrunk grids in UTM projection
DROP FUNCTION IF EXISTS get_shrunk_grids_in_utm;
CREATE FUNCTION get_shrunk_grids_in_utm(project_id INT, shrink_distance DOUBLE PRECISION, grid_type TEXT DEFAULT 'ORIGINAL', is_percentage boolean DEFAULT FALSE)
RETURNS TABLE(gid INTEGER, taskid INTEGER, geom GEOMETRY) AS $$
DECLARE
	do_mockup_grid BOOLEAN;
BEGIN
	IF grid_type = 'MOCKUP-POLY' THEN
		IF NOT is_percentage THEN
			RAISE EXCEPTION 'Mockup polygon grids are only generated by percentage';
		END IF;

		RETURN QUERY
		WITH utm_grids AS (
			SELECT 0 as gid, ggiu.taskid, ggiu.geom
			FROM get_grids_in_utm(project_id, FALSE) AS ggiu
		),
		mockup_poly_grids AS (
			SELECT mpg.taskid, ST_Union(mpg.geom) AS geom
			FROM mockup_polygon_grids AS mpg
			WHERE mpg.project_id = get_shrunk_grids_in_utm.project_id
			AND mpg.percentage_covered = shrink_distance
			GROUP BY mpg.taskid
		)
		SELECT ug.gid, ug.taskid, ST_Difference(ug.geom, mg.geom) AS geom
		FROM utm_grids ug
		JOIN mockup_poly_grids mg ON ug.taskid = mg.taskid;
	ELSE
		IF grid_type = 'MOCKUP' THEN
			do_mockup_grid := TRUE;
		ELSE
			do_mockup_grid := FALSE;
		END IF;

		RETURN QUERY
		WITH utm_grids AS (
			SELECT 0 as gid, ggiu.taskid, ggiu.geom
			FROM get_grids_in_utm(project_id, do_mockup_grid) AS ggiu
		)
		SELECT utm_grids.gid, utm_grids.taskid, shrink_geometry(utm_grids.geom, shrink_distance, is_percentage) AS geom
		FROM utm_grids;
	END IF;
END;
$$ LANGUAGE plpgsql;

