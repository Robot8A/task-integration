-- Get buildings part of one or more tasks
DROP FUNCTION IF EXISTS get_buildings_from_tasks;
CREATE FUNCTION get_buildings_from_tasks(project_id INT, task_ids INT[])
RETURNS TABLE(osm_id INTEGER, geom GEOMETRY) AS $$
BEGIN
	RETURN QUERY
	SELECT b.osm_id, b.geom
	FROM buildings_utm b
	WHERE b.project_id = get_buildings_from_tasks.project_id
	AND EXISTS (
		SELECT 1
		FROM get_grids_in_utm(get_buildings_from_tasks.project_id) hg
		WHERE hg.taskid = ANY(get_buildings_from_tasks.task_ids)
		AND ST_Intersects(b.geom, hg.geom)
	);
END $$ LANGUAGE plpgsql;

-- Returns an accurate UTM zone number for a given project
DROP FUNCTION IF EXISTS get_utm_zone;
CREATE FUNCTION get_utm_zone(project_id INT)
RETURNS INT AS $$
DECLARE
	utm_epsg INTEGER;
BEGIN
	SELECT uz.utm_epsg INTO utm_epsg FROM utm_zones uz WHERE uz.project_id = get_utm_zone.project_id;

	IF utm_epsg IS NOT NULL THEN
		RETURN utm_epsg;
	END IF;

	-- Calculate the UTM EPSG code
	SELECT calculate_utm_zone(union_gg.geom)::INTEGER INTO utm_epsg
	FROM (
    	SELECT ST_Union(CASE WHEN ST_IsValid(gg.geom) THEN gg.geom ELSE ST_MakeValid(gg.geom) END) AS geom
    	FROM get_grids(project_id) AS gg
	) AS union_gg
	LIMIT 1;

	INSERT INTO utm_zones (utm_epsg, project_id) VALUES (utm_epsg, project_id);

	RETURN utm_epsg;
END;
$$ LANGUAGE plpgsql;

