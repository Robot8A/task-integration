-- Returns an accurate UTM zone number for a given geometry
DROP FUNCTION IF EXISTS calculate_utm_zone;
CREATE FUNCTION calculate_utm_zone(geometry GEOMETRY)
RETURNS TEXT AS $$
DECLARE
	lat NUMERIC;
	lon NUMERIC;
	zone_number INT;
	epsg_number TEXT;
BEGIN
	-- Calculate the centroid of the bounding box of the geometry
	SELECT ST_Y(ST_Centroid(ST_Extent(geometry))), ST_X(ST_Centroid(ST_Extent(geometry)))
	INTO lat, lon;

	-- Calculate the UTM zone number
	zone_number := FLOOR((lon + 180) / 6) + 1;

	-- Determine the EPSG code based on latitude
	IF lat >= 0 THEN
    	epsg_number := '326' || LPAD(zone_number::TEXT, 2, '0');
	ELSE
    	epsg_number := '327' || LPAD(zone_number::TEXT, 2, '0');
	END IF;

	RETURN epsg_number;
END;
$$ LANGUAGE plpgsql;

-- Shrinks a geometry by a given distance or percentage
DROP FUNCTION IF EXISTS shrink_geometry;
CREATE FUNCTION shrink_geometry(
    geom geometry, 
    shrink_value double precision, 
    is_percentage boolean DEFAULT FALSE
)
RETURNS geometry AS $$
DECLARE
    scaled_geom geometry;
    scale_factor double precision;
BEGIN

	IF shrink_value = 0 OR ST_Area(geom) = 0 THEN
		RETURN geom;
	END IF;

    IF is_percentage THEN
		IF shrink_value = 100 THEN
			RETURN ST_MakeEmpty();
		END IF;

        -- Convert percentage to a factor between 0 and 1
        scale_factor := 1 - (shrink_value / 100.0);
        
        -- Dilate back the geometry by the scale factor
        scaled_geom := ST_Dilate(geom, scale_factor);
    ELSE
        -- Apply the negative buffer to shrink the geometry by a fixed distance
        scaled_geom := ST_Buffer(geom, -shrink_value);
    END IF;

    RETURN scaled_geom;
END;
$$ LANGUAGE plpgsql;


-- Returns true if all grids are fully adjacent and not overlapping
DROP FUNCTION IF EXISTS project_has_fully_adjacent_cells;
CREATE FUNCTION project_has_fully_adjacent_cells(project_id INT)
RETURNS BOOLEAN AS $$
DECLARE
	num_clusters INT;
	overlapping_count INT;
BEGIN
	-- Count the number of unique clusters where geometries intersect
	SELECT COUNT(DISTINCT cluster) INTO num_clusters
	FROM (
		SELECT
			unnest(ST_ClusterIntersecting(geom)) AS cluster
		FROM (
			SELECT 
				CASE 
					WHEN ST_IsValid(geom) THEN geom 
					ELSE ST_MakeValid(geom) 
				END AS geom
			FROM get_grids(project_id)
		) AS valid_geoms
	) AS clustered_areas;

	-- Count the number of overlapping geometries
	SELECT COUNT(*) INTO overlapping_count
	FROM (
		SELECT g1.geom
		FROM (
			SELECT 
				CASE 
					WHEN ST_IsValid(geom) THEN geom 
					ELSE ST_MakeValid(geom) 
				END AS geom, taskid
			FROM get_grids(project_id)
		) g1, (
			SELECT 
				CASE 
					WHEN ST_IsValid(geom) THEN geom 
					ELSE ST_MakeValid(geom) 
				END AS geom, taskid
			FROM get_grids(project_id)
		) g2
		WHERE g1.taskid <> g2.taskid AND ST_Overlaps(g1.geom, g2.geom)
	) AS overlapping_areas;

	-- Return true if all geometries are in a single cluster and there are no overlaps, otherwise false
	RETURN num_clusters = 1 AND overlapping_count = 0;
END;
$$ LANGUAGE plpgsql;

